/**
 * Conversation Exporter - Handle export functionality for chat conversations
 */
define(['jquery'], function ($) {
    'use strict';

    // Model pricing configuration (frontend)
    var MODEL_PRICING = {
        'claude-opus-4-5': 0.015,
        'claude-opus': 0.015,
        'claude-3-opus': 0.015,
        'claude-3-sonnet': 0.003,
        'claude-3.5-sonnet': 0.003,
        'claude-sonnet': 0.003,
        'gpt-4': 0.03,
        'gpt-4-turbo': 0.01,
        'gpt-4o': 0.005,
        'gpt-3.5-turbo': 0.0005,
        'ollama': 0.00,
        'mistral': 0.0001,
        'llama': 0.00
    };

    return function () {
        // Export the calculator to window for use by admin-chat.js
        window.gtaiExporter = {
            /**
             * Calculate estimated cost from token count
             */
            calculateCost: function (tokens, model) {
                var model_lower = (model || '').toLowerCase();
                var price = MODEL_PRICING[model_lower] || 0;
                return (tokens * price / 1000).toFixed(4);
            },

            /**
             * Format cost as currency
             */
            formatCost: function (cost) {
                return '$' + (parseFloat(cost) || 0).toFixed(2);
            },

            /**
             * Export conversation as JSON
             */
            exportAsJSON: function (messages, metadata) {
                var data = {
                    metadata: {
                        created_at: new Date().toISOString(),
                        model: metadata.model || 'unknown',
                        provider: metadata.provider || 'unknown',
                        total_tokens: metadata.total_tokens || 0,
                        estimated_cost: metadata.estimated_cost || '$0.00'
                    },
                    conversation: messages.map(function (msg) {
                        return {
                            role: msg.role,
                            content: msg.content,
                            timestamp: msg.timestamp || new Date().toISOString(),
                            tokens: msg.tokens || 0
                        };
                    })
                };

                return JSON.stringify(data, null, 2);
            },

            /**
             * Export conversation as TEXT
             */
            exportAsTXT: function (messages, metadata) {
                var lines = [];

                lines.push('═══════════════════════════════════════════════════');
                lines.push('DATA QUERY CONVERSATION REPORT');
                lines.push('═══════════════════════════════════════════════════');
                lines.push('');
                lines.push('Generated: ' + new Date().toLocaleString());
                lines.push('Model: ' + (metadata.model || 'unknown'));
                lines.push('Provider: ' + (metadata.provider || 'unknown'));
                lines.push('');
                lines.push('Tokens Used: ' + (metadata.total_tokens || 0));
                lines.push('Estimated Cost: ' + (metadata.estimated_cost || '$0.00'));
                lines.push('');
                lines.push('═══════════════════════════════════════════════════');
                lines.push('CONVERSATION');
                lines.push('═══════════════════════════════════════════════════');
                lines.push('');

                messages.forEach(function (msg, index) {
                    var role = msg.role === 'user' ? 'YOU' : 'ASSISTANT';
                    var time = msg.timestamp ? new Date(msg.timestamp).toLocaleTimeString() : '';
                    var tokens = msg.tokens ? ' [' + msg.tokens + ' tokens]' : '';

                    lines.push(role + ' (' + time + ')' + tokens + ':');
                    lines.push(msg.content);
                    lines.push('');
                });

                lines.push('═══════════════════════════════════════════════════');
                lines.push('SUMMARY');
                lines.push('═══════════════════════════════════════════════════');
                lines.push('Total Messages: ' + messages.length);
                lines.push('Total Tokens: ' + (metadata.total_tokens || 0));
                lines.push('Estimated Cost: ' + (metadata.estimated_cost || '$0.00'));
                lines.push('');
                lines.push('Generated by Data Query Assistant');
                lines.push('═══════════════════════════════════════════════════');

                return lines.join('\n');
            },

            /**
             * Trigger file download
             */
            downloadFile: function (content, filename, mimeType) {
                var blob = new Blob([content], { type: mimeType || 'text/plain; charset=utf-8' });
                var url = URL.createObjectURL(blob);
                var link = document.createElement('a');

                link.href = url;
                link.download = filename || 'conversation.txt';
                link.style.display = 'none';

                document.body.appendChild(link);
                link.click();

                // Cleanup
                setTimeout(function () {
                    document.body.removeChild(link);
                    URL.revokeObjectURL(url);
                }, 100);
            }
        };
    };
});
